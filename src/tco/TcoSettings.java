    /** Reloads the settings file. */
    public static void reload() {
        loaded = false;
        load();
        // LunaLib values win over the file
        if (lunaEnabled()) TcoLuna.apply();
    }

    public static boolean lunaEnabled() {
        try {
            return Global.getSettings().getModManager().isModEnabled("lunalib");
        } catch (RuntimeException e) {
            return false;
        }
    }

    private static void readList(JSONObject json, String name, List<String> into) {
        JSONArray array = json.optJSONArray(name);
        if (array == null) return;
        into.clear();
        for (int i = 0; i < array.length(); i++) {
            String id = array.optString(i, "").trim();
            if (!id.isEmpty()) into.add(id);
        }
    }

    private static int key(JSONObject json, String name, int fallback) {
        String value = json.optString(name, "");
        if (value.isEmpty()) return fallback;
        int index = InputKeys.parse(value);
        return index == Keyboard.KEY_NONE ? fallback : index;
    }
